#!/usr/bin/env node
/**
 * Writes public/_redirects from the `redirect` frontmatter field.
 *
 * gatsby-node.js calls createRedirect() for entries carrying a `redirect`
 * field, but createRedirect is inert without a plugin that writes the
 * redirects to disk. The previous host injected such a plugin at build time,
 * which is why no equivalent appears in package.json -- and why these
 * redirects would have vanished silently when the site moved.
 *
 * Output is a plain text file of `from to 301` lines, which Cloudflare parses
 * directly.
 *
 * Run after `gatsby build`, so it writes into an existing public/.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const STATES_DIR = path.join(ROOT, 'content', 'states');
const OUT_FILE = path.join(ROOT, 'public', '_redirects');

// Cloudflare's ceiling for static rules in a _redirects file.
const STATIC_REDIRECT_LIMIT = 2000;

/**
 * Pull the `redirect` value out of a markdown file's frontmatter.
 *
 * Returns null when absent or empty. The empty case is not hypothetical --
 * at least one entry carries `redirect: ''`, and gatsby-node.js skips it via
 * `if (redirect && redirect !== null)`. Emitting a rule for it would produce
 * a _redirects line with no source path.
 */
function readRedirect(file) {
  const source = fs.readFileSync(file, 'utf8');
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) return null;

  const line = frontmatter[1]
    .split(/\r?\n/)
    .find((l) => /^redirect:/.test(l));
  if (!line) return null;

  const value = line
    .slice('redirect:'.length)
    .trim()
    .replace(/^['"]|['"]$/g, '')
    .trim();

  return value || null;
}

/**
 * Mirror of the slug built in gatsby-node.js onCreateNode: the `states`
 * source instance is prefixed with `/s`, and createFilePath turns
 * content/states/<dir>/index.md into `/<dir>/`.
 */
function slugForEntry(dirName) {
  return `/s/${dirName}/`;
}

function main() {
  const publicDir = path.join(ROOT, 'public');
  if (!fs.existsSync(publicDir)) {
    console.error('public/ not found -- run `gatsby build` before this script.');
    process.exit(1);
  }

  const entries = fs
    .readdirSync(STATES_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const rules = [];
  const seen = new Map();

  entries.forEach((dirName) => {
    const file = path.join(STATES_DIR, dirName, 'index.md');
    if (!fs.existsSync(file)) return;

    const from = readRedirect(file);
    if (!from) return;

    if (!from.startsWith('/')) {
      console.warn(`Skipping non-absolute redirect in ${dirName}: ${from}`);
      return;
    }

    if (seen.has(from)) {
      console.warn(
        `Duplicate redirect source ${from} in ${dirName}, already claimed by ${seen.get(from)}`
      );
      return;
    }

    seen.set(from, dirName);
    rules.push(`${from} ${slugForEntry(dirName)} 301`);
  });

  if (rules.length > STATIC_REDIRECT_LIMIT) {
    console.error(
      `${rules.length} redirects exceeds Cloudflare's ${STATIC_REDIRECT_LIMIT} static rule limit.`
    );
    process.exit(1);
  }

  const header = [
    '# Generated by scripts/generate-redirects.js -- do not edit by hand.',
    '# Source: the `redirect` frontmatter field in content/states/*/index.md',
    '',
  ].join('\n');

  fs.writeFileSync(OUT_FILE, `${header}${rules.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${rules.length} redirects to public/_redirects`);
}

main();
